#!/usr/bin/env python3
"""Rasterizes DejaVu Sans Bold into the anti-aliased glyph tables the drawn menu (overlay.cpp) uses.

    python3 tools/mkfont.py [font.ttf] > src/xbox/overlay_font.h

Three sizes for a 720-line front buffer (title, body, hint); overlay.cpp scales its layout to
other heights by choosing among them. Glyphs are printable ASCII. DejaVu fonts are under the
Bitstream Vera license (see THIRD_PARTY.md), which allows embedding.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZES = [("kFontHuge", 58), ("kFontLarge", 40), ("kFontMedium", 26), ("kFontSmall", 18)]
FIRST, LAST = 32, 126


def rasterize(size):
    font = ImageFont.truetype(FONT, size)
    ascent, descent = font.getmetrics()
    glyphs, pixels = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        advance = round(font.getlength(ch))
        w, h = max(0, right - left), max(0, bottom - top)
        offset = len(pixels)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
            pixels += img.tobytes()
        # x offset from the pen, y offset from the line top, width, height, advance, data offset
        glyphs.append((left, top, w, h, advance, offset))
    return ascent + descent, ascent, glyphs, pixels


def main():
    out = [
        "// Generated by tools/mkfont.py from DejaVu Sans Bold (Bitstream Vera license, see",
        "// THIRD_PARTY.md). Do not edit.",
        "#pragma once",
        "",
        "struct OverlayGlyph { signed char x, y; unsigned char w, h, advance; unsigned int offset; };",
        "struct OverlayFont {",
        "  int line_height, ascent, first, last;",
        "  const OverlayGlyph* glyphs;",
        "  const unsigned char* pixels;",
        "};",
        "",
    ]
    for name, size in SIZES:
        line, ascent, glyphs, pixels = rasterize(size)
        out.append(f"static const OverlayGlyph {name}Glyphs[] = {{")
        for g in glyphs:
            out.append("  {%d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        out.append(f"static const unsigned char {name}Pixels[{max(1, len(pixels))}] = {{")
        data = pixels or b"\0"
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const OverlayFont {name} = {{{line}, {ascent}, {FIRST}, {LAST}, "
                   f"{name}Glyphs, {name}Pixels}};")
        out.append("")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
